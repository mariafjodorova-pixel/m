  var AUX = ["съм", "си", "е", "сме", "сте", "са"];
  var BYAH = ["бях", "беше", "беше", "бяхме", "бяхте", "бяха"];
  var SHTYAH = ["щях", "щеше", "щеше", "щяхме", "щяхте", "щяха"];
  var BIH = ["бих", "би", "би", "бихме", "бихте", "биха"];
